        /**
         * Gets the enum name of a Salvation-only client Ex packet, when known.
         * @param salvationExId the unsigned extended opcode received from the client
         * @return the packet name from the Salvation protocol, or null when unknown or mapped
         */
        public static String getSalvationOnlyExName(int salvationExId)
        {
                if ((salvationExId < 0) || (salvationExId >= EX_CM_SALVATION_ONLY_NAMES.length))
                {
                        return null;
                }
                
                return EX_CM_SALVATION_ONLY_NAMES[salvationExId];
        }

        /**
         * Checks if the given protocol revision is handled by this adapter.
         * @param version the client protocol revision
         * @return true if the adapter is enabled and the revision matches
         */
        public static boolean isEnabledFor(int version)
        {
                return ServerConfig.ENABLE_SALVATION_PROTOCOL && (version == SALVATION_PROTOCOL_REVISION);
        }
        
        /**
         * Translates an incoming client Ex (0xD0) opcode from the Salvation space
         * to the local High Five handler space.
         * @param salvationExId the unsigned extended opcode received from the client
         * @return the local ExClientPackets id, or -1 when the packet has no local counterpart
         */
        public static int translateIncomingExId(int salvationExId)
        {
                if ((salvationExId < 0) || (salvationExId >= EX_CM_SALVATION_TO_LOCAL.length))
                {
                        return -1;
                }
                
                return EX_CM_SALVATION_TO_LOCAL[salvationExId];
        }
        
        /**
         * Translates the opcode fields of an outgoing server packet from the local
         * High Five space to the Salvation space, in place, before encryption.<br>
         * Regular opcodes pass unchanged; extended (0xFE xx) second ids are remapped
         * when a Salvation counterpart exists.
         * @param buffer the packet buffer (payload starts at the given offset)
         * @param offset the offset of the first opcode byte inside the buffer
         */
        public static void translateOutgoingOpcode(WriteBuffer buffer, int offset)
        {
                try
                {
                        final int id1 = buffer.readByte(offset) & 0xFF;
                        if (id1 == 0xFE)
                        {
                                final int id2 = buffer.readShort(offset + 1) & 0xFFFF;
                                if ((id2 >= 0) && (id2 < EX_SM_LOCAL_TO_SALVATION.length))
                                {
                                        final int mapped = EX_SM_LOCAL_TO_SALVATION[id2];
                                        if (mapped >= 0)
                                        {
                                                buffer.writeShort(offset + 1, (short) mapped);
                                        }
                                }
                        }
                }
                catch (Exception e)
                {
                        // A broken buffer must never break the I/O thread; the packet is sent unchanged.
                }
        }
